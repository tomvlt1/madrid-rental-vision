def get_zone(location: str) -> str:
    """Returns 'Otro' if no match."""
    if not location:
        return "Otro"
    loc_lower = location.lower()
    for keyword, zone in ZONE_MAP.items():
        if keyword in loc_lower:
            return zone
    return "Otro"
